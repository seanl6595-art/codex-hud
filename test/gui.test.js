'use strict';
const test = require('node:test'), assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path');
const { fixture, meta, token } = require('./helpers');
const { startServer } = require('../lib/gui/server');
const { parseArgs } = require('../lib/cli');
test('GUI CLI options preserve defaults and reject unrelated options', () => {
  assert.equal(parseArgs([]).command, 'hud');
  assert.equal(parseArgs(['gui', '--no-open', '--port', '0', '--db', 'local.sqlite3']).flags.port, '0');
  for (const args of [['stats', '--no-open'], ['hud', '--port', '12'], ['gui', '--port', '-1'], ['gui', '--port', '65536'], ['gui', '--once']]) assert.throws(() => parseArgs(args));
});
test('GUI serves loopback assets, protects local API, and keeps reads opt-in', async t => {
  const f = fixture(t), assets = path.join(f.home, 'assets'), dbPath = path.join(f.home, 'db', 'test.sqlite3');
  fs.mkdirSync(assets); fs.writeFileSync(path.join(assets, 'index.html'), '<html>synthetic GUI asset</html>');
  f.write('sessions/a.jsonl', [meta('a'), token()]);
  const gui = await startServer({ home: f.home, dbPath, assets, port: 0, interval: 1000 });
  t.after(() => gui.close());
  assert.equal(gui.server.address().address, '127.0.0.1');
  assert.match(await (await fetch(gui.url)).text(), /synthetic GUI/);
  const bootstrap = await (await fetch(gui.url + '/api/bootstrap')).json();
  const headers = { 'x-codex-hud-token': bootstrap.token };
  const request = (url, options = {}) => fetch(gui.url + url, { headers, ...options });
  assert.equal((await fetch(gui.url + '/api/stats')).status, 403);
  assert.equal((await request('/api/recorder', { headers: { ...headers, Origin: 'https://untrusted.example' } })).status, 403);
  assert.equal(await new Promise(resolve => require('node:http').get(gui.url + '/api/bootstrap', { headers: { Host: 'untrusted.example' } }, res => { res.resume(); resolve(res.statusCode); })), 403);
  assert.equal((await request('/api/stats')).status, 404);
  assert.equal(fs.existsSync(dbPath), false);
  const list = await (await request('/api/sessions')).json();
  assert.equal(list.sessions[0].id, 'a'); assert.equal('file' in list.sessions[0], false);
  assert.equal((await request('/api/sessions/not-found')).status, 404);
  const detail = await (await request('/api/sessions/a')).json(); assert.equal(detail.telemetry.lastRequest.inputTokens, 1000);
  assert.equal((await request('/api/stats?range=lookback&hours=bad')).status, 400);
  assert.equal((await request('/api/stats?range=custom&from=bad')).status, 400);
  assert.equal((await request('/api/recorder/start')).status, 404);
  await request('/api/recorder/sync', { method: 'POST' });
  assert.equal(fs.existsSync(dbPath), true);
  let status = await (await request('/api/recorder')).json();
  assert.equal(status.running, false); assert.equal(status.events, 1); assert.ok(status.lastSync);
  await request('/api/recorder/start', { method: 'POST' });
  status = await (await request('/api/recorder')).json(); assert.equal(status.running, true);
  await request('/api/recorder/stop', { method: 'POST' });
  status = await (await request('/api/recorder')).json(); assert.equal(status.running, false); assert.equal(status.events, 1);
  const heatmap = await (await request('/api/heatmap')).json(); assert.equal(heatmap.buckets.length, 84);
  assert.equal((await request('/api/recorder/sync', { method: 'POST', headers: { ...headers, 'Content-Length': '1025' }, body: 'x'.repeat(1025) })).status, 413);
});
